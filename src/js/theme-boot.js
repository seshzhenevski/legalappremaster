// theme-boot.js
// Ранняя установка темы ДО первой отрисовки — чтобы при запуске в тёмной теме
// не мелькал светлый экран (ТЗ: «Отсутствие вспышки»).
//
// Это отдельный обычный (не module) скрипт, подключённый в <head> как
// блокирующий: CSP приложения запрещает инлайн-скрипты (script-src 'self'),
// поэтому раннюю логику нельзя положить прямо в <head> тегом <script>…</script>.
// Источник истины — settings.json (читается асинхронно позже в theme.js), а
// здесь используется синхронное зеркало в localStorage.
(function () {
  try {
    if (localStorage.getItem("theme") === "dark") {
      document.documentElement.classList.add("dark");
    }
  } catch (error) {
    // localStorage недоступен (приватный режим и т. п.) — стартуем в светлой.
  }
})();
