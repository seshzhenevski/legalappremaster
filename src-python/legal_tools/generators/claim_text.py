"""
generators/claim_text.py
────────────────────────
Единый источник текста досудебной претензии (по образцу «Претензия драфт.pdf»).

Здесь собран весь текст письма — заголовок, тело и подписант, — чтобы
DOCX- и PDF-генераторы рендерили ОДНО И ТО ЖЕ содержимое и не расходились.
Каждый абзац возвращается как список «ранов» (кусочков) вида (текст, bold),
а конкретное оформление (шрифт, выравнивание) добавляет уже сам генератор.
"""
from __future__ import annotations

from datetime import date
from decimal import Decimal
from typing import List, Optional, Tuple

from ..config import LAW_PLAINTIFF_NAME
from ..core.duty import plural_form
from ..core.formatting import fmt

# Один «ран» абзаца: текст + признак жирного. Абзац — список ранов.
Run = Tuple[str, bool]
Paragraph = List[Run]

LETTER_TITLE = "Уведомление о необходимости урегулирования в досудебном порядке"


def format_claim_number(raw: str) -> str:
    """
    Приводит номер претензии к «голому» виду без префикса «№» и пробелов.

    Пользователь может ввести «№57», «57» или « 57 » — во всех случаях
    возвращается «57». Автосформированный номер приходит уже нормализованным.
    Возвращает пустую строку, если номер не задан.
    """
    return (raw or "").strip().lstrip("№N#").strip()


def money_phrase(amount: Decimal) -> str:
    """
    Форматирует сумму долга с корректным словом «рубль/рубля/рублей».

    Например Decimal('269789.80') → «269 789,80 рублей». Слово согласуется
    по целой части суммы (та же логика, что в исковом заявлении).
    """
    word = plural_form(int(amount), "рубль", "рубля", "рублей")
    return f"{fmt(amount)} {word}"


def letter_reference(claim_number: str, claim_date: date) -> str:
    """
    Собирает строку исходящего реквизита письма: «Исх. № 57 от 13.07.2026».
    """
    number = format_claim_number(claim_number) or "—"
    return f"Исх. № {number} от {claim_date:%d.%m.%Y}"


def contract_phrase(contract_number: str, contract_date: Optional[date]) -> str:
    """
    Собирает описание договора для тела письма.

    Возвращает «№ 2706/23-АР от 27.06.2023», «№ 2706/23-АР» (если дата
    неизвестна) или «№ ______» (если номер не задан) — чтобы письмо
    оставалось читаемым при неполных данных.
    """
    number = (contract_number or "").strip()
    if not number:
        return "№ ______"
    if contract_date is not None:
        return f"№ {number} от {contract_date:%d.%m.%Y}"
    return f"№ {number}"


def signatory() -> Tuple[str, str]:
    """Возвращает пару (должность, ФИО) подписанта письма."""
    from ..config import CLAIM_SIGNATORY_TITLE, CLAIM_SIGNATORY_NAME
    return CLAIM_SIGNATORY_TITLE, CLAIM_SIGNATORY_NAME


